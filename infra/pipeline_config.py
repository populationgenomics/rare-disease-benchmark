"""Writes what the build pipeline needs to run against one stack, from that stack's outputs.

    uv run --group infra python infra/pipeline_config.py --stack <stack> --dragen-image-tag <tag>

writes two files into build/, both ignored by git:

- <stack>.params.yaml, the deployment's params: the references, the DRAGEN key's secret, the DRAGEN image and the
  output directory. Every
  launch takes it, with `-params-file` or as the params file of a Seqera launch.
- <stack>.site.config, for launching from a workstation (`-profile google -c <stack>.site.config`): project, region,
  network, service account and work directory, which a Seqera compute environment supplies itself.

Run it again after `pulumi up` changes an output, or to switch the DRAGEN image.
"""

from __future__ import annotations

import argparse
import pathlib
import re
from collections.abc import Mapping

import references
import stack_outputs
import yaml

_INFRA = pathlib.Path(__file__).resolve().parent
_BUILD = _INFRA.parent / 'build'

PARAMS_OUTPUTS = ('dataBucket', 'outputDir', 'imagePrefix', 'dragenApiKeySecret')
SITE_OUTPUTS = ('project', 'region', 'workDir', 'network', 'subnetwork', 'serviceAccountEmail')

_TAG = re.compile(r'[\w][\w.-]{0,127}')


def params(outputs: Mapping[str, str], *, stack: str, dragen_image_tag: str) -> dict[str, str]:
    """The deployment's params, as the pipeline's params block names them."""
    stack_outputs.require(outputs, PARAMS_OUTPUTS, stack=stack)
    if not _TAG.fullmatch(dragen_image_tag):
        raise ValueError(f'{dragen_image_tag!r} is not a valid image tag')
    data = outputs['dataBucket']
    return {
        'dragen_reference': f'{data}/{references.DRAGEN_REFERENCE}',
        'cram_reference': f'{data}/{references.CRAM_REFERENCE}',
        'dragen_api_key_secret': outputs['dragenApiKeySecret'],
        'dragen_container': f'{outputs["imagePrefix"]}/dragen:{dragen_image_tag}',
        'output_dir': outputs['outputDir'],
    }


def _quoted(value: str) -> str:
    # Every value is a GCP name, path or URL; anything that would need escaping in a Groovy string is a mistake.
    if re.search(r"['\\$\n]", value):
        raise ValueError(f'refusing to write {value!r} into the config')
    return f"'{value}'"


def site_config(outputs: Mapping[str, str], *, stack: str) -> str:
    """The Nextflow config for launching from a workstation against the stack."""
    stack_outputs.require(outputs, SITE_OUTPUTS, stack=stack)
    return f"""\
// Generated by infra/pipeline_config.py from the outputs of Pulumi stack {stack}. Do not edit; regenerate.

workDir = {_quoted(outputs['workDir'])}

google {{
    project = {_quoted(outputs['project'])}
    location = {_quoted(outputs['region'])}
    batch {{
        network = {_quoted(outputs['network'])}
        subnetwork = {_quoted(outputs['subnetwork'])}
        serviceAccountEmail = {_quoted(outputs['serviceAccountEmail'])}
    }}
}}
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--stack', required=True, help='the Pulumi stack to read the outputs of')
    parser.add_argument('--dragen-image-tag', required=True, help='the tag the DRAGEN image was pushed under')
    args = parser.parse_args()
    outputs = stack_outputs.read(args.stack)
    params_file = _BUILD / f'{args.stack}.params.yaml'
    header = f'# Generated by infra/pipeline_config.py from the outputs of Pulumi stack {args.stack}; regenerate.\n'
    written = params(outputs, stack=args.stack, dragen_image_tag=args.dragen_image_tag)
    params_file.write_text(header + yaml.safe_dump(written, sort_keys=False))
    site_file = _BUILD / f'{args.stack}.site.config'
    site_file.write_text(site_config(outputs, stack=args.stack))
    for path in (params_file, site_file):
        print(f'wrote {path.relative_to(_INFRA.parent)}')


if __name__ == '__main__':
    main()
