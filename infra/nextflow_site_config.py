"""Writes the build pipeline's Nextflow site config for one stack, from that stack's outputs.

    uv run --group infra python infra/nextflow_site_config.py --stack <stack> --dragen-image-tag <tag>

writes build/<stack>.site.config, which git ignores, for `nextflow run main.nf -profile google -c <stack>.site.config`.
Run it again after `pulumi up` changes an output, or to switch the DRAGEN image.
"""

from __future__ import annotations

import argparse
import pathlib
import re
from collections.abc import Mapping

import references
import stack_outputs

_INFRA = pathlib.Path(__file__).resolve().parent
_BUILD = _INFRA.parent / 'build'

REQUIRED_OUTPUTS = (
    'project',
    'region',
    'workDir',
    'outputDir',
    'dataBucket',
    'network',
    'subnetwork',
    'serviceAccountEmail',
    'imagePrefix',
    'dragenApiKeySecret',
)

_TAG = re.compile(r'[\w][\w.-]{0,127}')


def _quoted(value: str) -> str:
    # Every value is a GCP name, path or URL; anything that would need escaping in a Groovy string is a mistake.
    if re.search(r"['\\$\n]", value):
        raise ValueError(f'refusing to write {value!r} into the config')
    return f"'{value}'"


def render(outputs: Mapping[str, str], *, stack: str, dragen_image_tag: str) -> str:
    """The Nextflow config for a stack with the given outputs."""
    stack_outputs.require(outputs, REQUIRED_OUTPUTS, stack=stack)
    if not _TAG.fullmatch(dragen_image_tag):
        raise ValueError(f'{dragen_image_tag!r} is not a valid image tag')
    data = outputs['dataBucket']
    return f"""\
// Generated by infra/nextflow_site_config.py from the outputs of Pulumi stack {stack}. Do not edit; regenerate.

workDir = {_quoted(outputs['workDir'])}
outputDir = {_quoted(outputs['outputDir'])}

google {{
    project = {_quoted(outputs['project'])}
    location = {_quoted(outputs['region'])}
    batch {{
        network = {_quoted(outputs['network'])}
        subnetwork = {_quoted(outputs['subnetwork'])}
        serviceAccountEmail = {_quoted(outputs['serviceAccountEmail'])}
    }}
}}

process {{
    withLabel: dragen {{
        container = {_quoted(f'{outputs["imagePrefix"]}/dragen:{dragen_image_tag}')}
    }}
}}

params {{
    dragen_reference = {_quoted(f'{data}/{references.DRAGEN_REFERENCE}')}
    cram_reference = {_quoted(f'{data}/{references.CRAM_REFERENCE}')}
    dragen_api_key_secret = {_quoted(outputs['dragenApiKeySecret'])}
}}
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--stack', required=True, help='the Pulumi stack to read the outputs of')
    parser.add_argument('--dragen-image-tag', required=True, help='the tag the DRAGEN image was pushed under')
    args = parser.parse_args()
    target = _BUILD / f'{args.stack}.site.config'
    target.write_text(render(stack_outputs.read(args.stack), stack=args.stack, dragen_image_tag=args.dragen_image_tag))
    print(f'wrote {target.relative_to(_INFRA.parent)}')


if __name__ == '__main__':
    main()
